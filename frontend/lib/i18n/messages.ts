export const messages: Record<Locale, Record<string, string>> = { en, zh };

/** Narrow an arbitrary string (cookie, header) to a supported locale. */
export const normalizeLocale = (value: string | null | undefined): Locale | null => {
	if (!value) return null;
	const lower = value.toLowerCase();
	if (lower.startsWith('zh')) return 'zh';
	if (lower.startsWith('en')) return 'en';
	return null;
};

/** Pick a locale from an Accept-Language header, honouring q-values loosely. */
export const localeFromAcceptLanguage = (header: string | null | undefined): Locale => {
	if (!header) return DEFAULT_LOCALE;
	// Good enough for en/zh: the first supported tag wins, English otherwise.
	for (const part of header.split(',')) {
		const tag = part.split(';')[0]?.trim();
		const match = normalizeLocale(tag);
		if (match) return match;
	}
	return DEFAULT_LOCALE;
};

export const translate = (
	locale: Locale,
	key: string,
	vars?: Record<string, string | number>,
): string => {
	const template = messages[locale][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
	if (!vars) return template;
	return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
		name in vars ? String(vars[name]) : whole,
	);
};
