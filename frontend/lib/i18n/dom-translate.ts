// Pure DOM translation helpers, deliberately free of React so they can be
// exercised by a test without a browser (see the unit check in the deployment
// notes). The React wrapper only decides *when* to run this.

import { messages } from './messages';

/** Exact-match dictionary: English source text -> Chinese. */
// Namespaced keys look like `nav.chat` / `chat.placeholder`. Matching that shape
// exactly (instead of "contains a dot") matters: English sentences carry their
// own periods, and a naive check filtered every one of them out.
const NAMESPACED = /^[a-z][A-Za-z0-9]*(\.[A-Za-z0-9]+)+$/;

export const PHRASES: Record<string, string> = Object.fromEntries(
	Object.entries(messages.zh).filter(([key]) => !NAMESPACED.test(key)),
);

const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'] as const;

/** Never rewrite these: code, SQL, user input, and table payloads. */
const SKIP_TAGS = new Set([
	'CODE',
	'PRE',
	'SCRIPT',
	'STYLE',
	'TEXTAREA',
	'INPUT',
	'TD',
	'SVG',
	'PATH',
]);

/** Verb + entity-name labels. The entity is data and keeps its language. */
const PATTERNS: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
	[/^Actions for (.+)$/, (m) => `${m[1]} 的操作`],
	[/^Open (.+)$/, (m) => `打开 ${m[1]}`],
	[/^Close (.+)$/, (m) => `关闭 ${m[1]}`],
	[/^Edit (.+)$/, (m) => `编辑 ${m[1]}`],
	[/^Delete (.+)$/, (m) => `删除 ${m[1]}`],
	[/^Remove (.+)$/, (m) => `移除 ${m[1]}`],
	[/^Revoke (.+)$/, (m) => `吊销 ${m[1]}`],
	[/^(.+) chart: (.+)$/, (m) => `${m[1]} 图表：${m[2]}`],
	[/^Viewing: (.+)$/, (m) => `当前查看：${m[1]}`],
	// 标签与取值被拆成两个节点时只剩这个前缀
	[/^Viewing:$/, () => '当前查看：'],
	[/^Last semantic compilation: (.+)$/, (m) => `最近一次语义编译：${m[1]}`],
	// 句子被内联 <code> 截断：只翻译前半句，数字由相邻节点渲染
	[
		/^Seconds a query generated by the agent may run before it is cancelled \($/,
		() => '智能体生成的查询最长可运行秒数（',
	],
];

export const translatePhrase = (text: string): string | null => {
	const exact = PHRASES[text];
	if (exact) return exact;
	for (const [pattern, build] of PATTERNS) {
		const match = text.match(pattern);
		if (match) return build(match);
	}
	return null;
};

const replaceAttrs = (el: Element): number => {
	let changed = 0;
	for (const attr of ATTRS) {
		const value = el.getAttribute(attr);
		if (!value) continue;
		const hit = translatePhrase(value.trim());
		if (hit) {
			el.setAttribute(attr, hit);
			changed += 1;
		}
	}
	return changed;
};

/**
 * Rewrite matching text nodes and labels under *root*.
 *
 * Returns the number of replacements, which is what the unit check asserts on.
 */
export const translateDom = (root: ParentNode, _doc: Document): number => {
	let changed = 0;

	const walk = (node: Node): void => {
		if (node.nodeType === 3) {
			const textNode = node as Text;
			const raw = textNode.nodeValue ?? '';
			// JSX often renders a label with a newline or a double space inside;
			// normalise before the lookup, then write the translation back whole.
			const text = raw.replace(/\s+/g, ' ').trim();
			const hit = text ? translatePhrase(text) : null;
			if (hit) {
				const start = raw.indexOf(text);
				textNode.nodeValue = raw.slice(0, start) + hit + raw.slice(start + text.length);
				changed += 1;
			}
			return;
		}
		if (node.nodeType !== 1) return;
		const el = node as Element;
		// A skipped tag keeps its text (code, SQL, cell payloads) but its labels
		// still deserve translation -- an <input placeholder> lives here.
		if (SKIP_TAGS.has(el.tagName)) {
			changed += replaceAttrs(el);
			return;
		}
		if (typeof el.closest === 'function' && el.closest('[data-no-translate]')) return;
		changed += replaceAttrs(el);
		el.childNodes.forEach(walk);
	};

	walk(root as Node);
	return changed;
};
